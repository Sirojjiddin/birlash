  const normalize = value => value.replace(/[‘’ʼ]/g, "'").replace(/[–—]/g, '-').replace(/\s+/g, ' ').trim();
  const translations = Object.fromEntries(rows.map(([uz, en, ru]) => [normalize(uz), { en, ru }]));
  const sourceText = new WeakMap();
  const sourceAttrs = new WeakMap();
  const translatedNodes = new WeakMap();
  const translatedAttrs = new WeakMap();
  const contentExclusions = '.chat-list,.chat-msg,.qopt,.qz-q,.av,.sticker,.sticker-pack,.reactbar,#reactBar,#pollQShow,#hNow,#rNow,#docName,[contenteditable="true"],input,textarea';
  let language = 'uz';

  function translatedValue(value) {
    const direct = translations[normalize(value)]?.[language];
    if (direct) return direct.trim();
    const prefix = value.match(/^(\s*(?:\p{Extended_Pictographic}|\p{S})(?:\uFE0F|\uFE0E)?\s+)([\s\S]+)$/u);
    if (!prefix) return null;
    const rest = translations[normalize(prefix[2])]?.[language];
    return rest ? `${prefix[1]}${rest.trim()}` : null;
  }

  function translateNode(node, isExternal = false, force = false) {
    if (!node || node.nodeType !== Node.TEXT_NODE || node.parentElement?.closest(contentExclusions)) return;
    const current = node.nodeValue;
    const expected = translatedNodes.get(node);
    if (!force && expected !== undefined && current === expected) return;
    if (!sourceText.has(node) || isExternal) {
      sourceText.set(node, current);
    }
    const original = sourceText.get(node);
    const translated = translatedValue(original) || original;
    const leading = /^[.,!?;:»”]/.test(translated) ? '' : (original.match(/^\s*/)?.[0] || '');
    const trailing = /[«“]$/.test(translated) ? '' : (original.match(/\s*$/)?.[0] || '');
    const result = `${leading}${translated}${trailing}`;
    if (node.nodeValue !== result) {
      node.nodeValue = result;
      translatedNodes.set(node, result);
    }
  }

  function translateAttribute(element, name, isExternal = false, force = false) {
    let originals = sourceAttrs.get(element);
    if (!originals) sourceAttrs.set(element, originals = new Map());
    const current = element.getAttribute(name);
    if (element.id === 'bxMode') return;
    const previous = translatedAttrs.get(element)?.get(name);
    if (!force && previous !== undefined && current === previous) return;
    if (!originals.has(name) || isExternal) {
      originals.set(name, current);
    }
    const translated = translatedValue(originals.get(name)) || originals.get(name);
    if (current !== translated) {
      element.setAttribute(name, translated);
      let rendered = translatedAttrs.get(element);
      if (!rendered) translatedAttrs.set(element, rendered = new Map());
      rendered.set(name, translated);
    }
  }

  function scan(root, isExternal = false, force = false) {
    if (root.nodeType === Node.TEXT_NODE) {
      translateNode(root, isExternal, force);
      return;
    }
    if (!(root instanceof Element || root instanceof Document)) return;
    const elements = root instanceof Element ? [root, ...root.querySelectorAll('*')] : [...root.querySelectorAll('*')];
    for (const element of elements) {
      if (!element.matches(contentExclusions) && !element.closest(contentExclusions)) {
        for (const node of element.childNodes) if (node.nodeType === Node.TEXT_NODE) translateNode(node, isExternal, force);
      }
      for (const name of ['placeholder', 'title', 'aria-label', 'data-tip']) {
        if (element.hasAttribute(name)) translateAttribute(element, name, isExternal, force);
      }
    }
  }

  function apply(lang) {
    language = ['uz', 'en', 'ru'].includes(lang) ? lang : 'uz';
    scan(document, false, true);
    document.documentElement.lang = language;
  }

  const observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === 'characterData') translateNode(record.target, true);
      else if (record.type === 'attributes') translateAttribute(record.target, record.attributeName, true);
      else record.addedNodes.forEach(node => scan(node));
    }
  });
  observer.observe(document.documentElement, {
    attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label', 'data-tip'],
    characterData: true, childList: true, subtree: true
  });
  window.addEventListener('bx:language', event => apply(event.detail));
  window.BX_I18N = { apply, get language() { return language; } };
